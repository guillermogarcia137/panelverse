  const rgb = (hex) =>
    hex
      .slice(1)
      .match(/../g)
      .map((n) => parseInt(n, 16));
  const luminance = (hex) =>
    rgb(hex)
      .map((n) => {
        const c = n / 255;
        return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
      })
      .reduce((s, c, i) => s + c * [0.2126, 0.7152, 0.0722][i], 0);
  // Calcula la relación de luminancia entre dos colores para comprobar si el texto se distingue del fondo.
  function contrast(a, b) {
    const x = luminance(a),
      y = luminance(b);
    return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
  }
  const mix = (a, b, ratio) =>
    "#" +
    rgb(a)
      .map((c, i) =>
        Math.round(c * (1 - ratio) + rgb(b)[i] * ratio)
          .toString(16)
          .padStart(2, "0"),
      )
      .join("");
  // Acerca el color al blanco o al negro hasta alcanzar el contraste objetivo, manteniendo la intención del tema.
  function readable(color, bg, target = 4.5) {
    const end =
      contrast("#ffffff", bg) > contrast("#111111", bg) ? "#ffffff" : "#111111";
    for (let i = 0; i <= 100; i++) {
      const c = mix(color, end, i / 100);
      if (contrast(c, bg) >= target) return c;
    }
    return end;
  }
  // Deriva los colores de controles, texto y bordes a partir de la paleta elegida.
  function palette(t) {
    const ink =
      contrast("#ffffff", t.accent) > contrast("#111111", t.accent)
        ? "#ffffff"
        : "#111111";
    return {
      ...t,
      muted: readable(t.muted, t.surface),
      link: readable(t.accent, t.surface),
      ink,
      soft: mix(t.surface, t.accent, 0.12),
      hover: mix(t.surface, t.accent, 0.2),
      sidebarText:
        contrast(t.text, t.sidebar) >= 4.5
          ? t.text
          : luminance(t.sidebar) < 0.3
            ? "#f5f5f5"
            : "#111111",
      sidebarMuted: readable(t.muted, t.sidebar),
      border: t.border,
      danger: t.mode === "light" ? "#b42332" : "#ffb4ad",
    };
  }

  globalThis.PanelVerseThemeKit = { themes, palette, contrast };
